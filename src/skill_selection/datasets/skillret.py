"""SkillRet (Cho, Kang and Kim, 2026, arXiv:2605.05726), a large-scale skill retrieval benchmark.

test : 6,006 skills, 4,392 queries generated by Claude Opus 4.6, 7,187 binary qrels
train: 10,123 skills, 63,259 queries generated by Qwen3.5-122B-A10B, 127,190 qrels
The train and test skill pools are disjoint. 46% of test queries need one skill, 40% two and 13% three.

Files are fetched from the Hugging Face Hub at a pinned commit because the Hub head is mutable.
"""
from __future__ import annotations

import shutil
import statistics
import urllib.request
from collections import Counter
from pathlib import Path
from typing import Dict, List, Tuple

from ..io import iter_jsonl
from ..schemas import QueryRecord, Qrels, SkillRecord

REPO = "ThakiCloud/SKILLRET"
REVISION = "6583d7d2ed07644d0fb8938ed8178f3a7dc42a12"   # branch main = v1.1, last modified 2026-09-25
REVISIONS = {"v1.1": REVISION, "v1.0": "3d0be4db875eae5987487645e38fbff39dc1970f"}
SPLITS = ("train", "test")
FILES = {
    "skills": "data/skills/{split}.jsonl",
    "queries": "data/queries/{split}.jsonl",
    "qrels": "data/qrels/{split}.jsonl",
}
# Query fields that reveal the answer. They are never copied into a QueryRecord.
GOLD_QUERY_FIELDS = frozenset({"skill_ids", "skill_names", "k"})
SKILL_METADATA_FIELDS = ("namespace", "domain", "primary_action", "primary_object", "stars", "installs",
                         "repo", "license")

# BM25 row of Table 3 in the paper (test split, in %), used as a sanity check for our own BM25.
PAPER_BM25 = {
    "NDCG@5": 46.47, "NDCG@10": 48.86, "NDCG@15": 49.90,
    "Recall@5": 50.09, "Recall@10": 56.55, "Recall@15": 59.95,
    "Completeness@5": 34.96, "Completeness@10": 41.09, "Completeness@15": 44.27,
}


def raw_dir(data_root: Path, revision: str = REVISION) -> Path:
    return Path(data_root) / "raw" / "skillret" / revision[:12]


def split_paths(split: str, data_root: Path, revision: str = REVISION) -> Dict[str, Path]:
    if split not in SPLITS:
        raise ValueError(f"unknown SkillRet split {split!r}; expected one of {SPLITS}")
    base = raw_dir(data_root, revision)
    return {subset: base / pattern.format(split=split) for subset, pattern in FILES.items()}


def download(split: str, data_root: Path, revision: str = REVISION, force: bool = False) -> Dict[str, Path]:
    """Fetch the three files of a split; files already on disk are kept unless force=True."""
    paths = split_paths(split, data_root, revision)
    for subset, dest in paths.items():
        if dest.exists() and not force:
            continue
        rel = FILES[subset].format(split=split)
        url = f"https://huggingface.co/datasets/{REPO}/resolve/{revision}/{rel}"
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_suffix(dest.suffix + ".part")
        req = urllib.request.Request(url, headers={"User-Agent": "agent-skill-selection"})
        with urllib.request.urlopen(req, timeout=60) as resp, open(tmp, "wb") as out:
            shutil.copyfileobj(resp, out, length=1 << 20)
        tmp.replace(dest)
    return paths


def _require(paths: Dict[str, Path]) -> None:
    missing = [str(p) for p in paths.values() if not p.exists()]
    if missing:
        raise FileNotFoundError("SkillRet files missing, run `skill-selection download skillret` first: "
                                + ", ".join(missing))


def load_skills(path: Path, split: str) -> List[SkillRecord]:
    skills = []
    for row in iter_jsonl(path):
        description = (row.get("description") or "").strip()
        # same fallback as the reference evaluation: a skill without skill_md is represented by its description
        body = (row.get("skill_md") or "").strip() or description
        category = "/".join(x for x in (row.get("major"), row.get("sub")) if x)
        skills.append(SkillRecord(
            id=str(row["id"]), name=(row.get("name") or "").strip(), description=description, body=body,
            source=f"skillret:{split}", category=category,
            metadata={k: row.get(k) for k in SKILL_METADATA_FIELDS if row.get(k) is not None},
        ))
    return skills


def load_queries(path: Path, split: str) -> List[QueryRecord]:
    queries = []
    for row in iter_jsonl(path):
        queries.append(QueryRecord(
            id=str(row["id"]), text=row["query"], source=f"skillret:{split}",
            group_id=str(row.get("original_id") or ""),
            metadata={"generator_model": row.get("generator_model")},
        ))
    return queries


def load_qrels(path: Path) -> Qrels:
    qrels: Qrels = {}
    for row in iter_jsonl(path):
        qrels.setdefault(str(row["query_id"]), {})[str(row["skill_id"])] = int(row["relevance"])
    return qrels


def load_split(split: str, data_root: Path, revision: str = REVISION
               ) -> Tuple[List[SkillRecord], List[QueryRecord], Qrels]:
    paths = split_paths(split, data_root, revision)
    _require(paths)
    return (load_skills(paths["skills"], split), load_queries(paths["queries"], split),
            load_qrels(paths["qrels"]))


def query_label_mismatches(queries_path: Path, qrels: Qrels) -> List[str]:
    """Query ids whose `skill_ids` field disagrees with the positive qrels (the two label sources of the release)."""
    bad = []
    for row in iter_jsonl(queries_path):
        qid = str(row["id"])
        from_query = {str(s) for s in row.get("skill_ids") or []}
        from_qrels = {s for s, r in qrels.get(qid, {}).items() if r > 0}
        if from_query != from_qrels:
            bad.append(qid)
    return bad


def split_stats(split: str, data_root: Path, revision: str = REVISION) -> Dict:
    paths = split_paths(split, data_root, revision)
    skills, queries, qrels = load_split(split, data_root, revision)
    skill_ids = {s.id for s in skills}
    query_ids = {q.id for q in queries}
    positives = {qid: [s for s, r in rels.items() if r > 0] for qid, rels in qrels.items()}
    n_pos = Counter(len(positives.get(q.id, [])) for q in queries)
    body_words = [len(s.body.split()) for s in skills]
    groups = Counter(q.group_id for q in queries if q.group_id)
    return {
        "split": split,
        "revision": revision,
        "n_skills": len(skills),
        "n_queries": len(queries),
        "n_qrels": sum(len(v) for v in qrels.values()),
        "positives_per_query": dict(sorted(n_pos.items())),
        "queries_without_positive": n_pos.get(0, 0),
        "qrels_unknown_skill": sum(1 for rels in qrels.values() for s in rels if s not in skill_ids),
        "qrels_unknown_query": sum(1 for q in qrels if q not in query_ids),
        "query_label_mismatches": len(query_label_mismatches(paths["queries"], qrels)),
        "skills_without_skill_md": sum(1 for s in skills if s.body == s.description),
        "body_words": {
            "mean": round(statistics.mean(body_words), 1) if body_words else 0,
            "median": statistics.median(body_words) if body_words else 0,
            "max": max(body_words, default=0),
        },
        "n_query_groups": len(groups),
        "max_queries_per_group": max(groups.values(), default=0),
        "top_categories": Counter(s.category for s in skills).most_common(10),
        "generator_models": dict(Counter(q.metadata.get("generator_model") for q in queries)),
    }
